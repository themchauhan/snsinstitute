export const locales = ['en', 'hi'] as const;
export type Locale = (typeof locales)[number];

export const isLocale = (v: string): v is Locale => (locales as readonly string[]).includes(v);

/** Builds a public URL path for a language. English has no prefix. */
export function href(lang: Locale, path = '/'): string {
  const clean = path === '/' ? '' : path.startsWith('/') ? path : `/${path}`;
  if (lang === 'en') return clean || '/';
  return `/hi${clean}`;
}

/** Picks the Hindi value when available, otherwise English. */
export function pick(lang: Locale, en: string | null | undefined, hi: string | null | undefined): string {
  if (lang === 'hi' && hi && hi.trim()) return hi;
  return en ?? '';
}

